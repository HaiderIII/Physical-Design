#!/bin/bash
# ============================================================================
# Block-Level Place & Route Runner
# ============================================================================
# Usage: ./run_pnr.sh <block_name> [phase]
#        ./run_pnr.sh uart           # Run full P&R for UART
#        ./run_pnr.sh uart floorplan # Run only floorplan
#        ./run_pnr.sh all            # Run P&R for all blocks
#
# Phases: floorplan, place, cts, route, all (default)
# Blocks: uart, spi, timer, gpio, bus, cpu
# ============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

# Sky130 paths
PLATFORM_DIR="$HOME/OpenROAD-flow-scripts/flow/platforms/sky130hd"

# Verify platform exists
if [ ! -d "$PLATFORM_DIR" ]; then
    echo "ERROR: Sky130 platform not found at $PLATFORM_DIR"
    exit 1
fi

# Generate TCL script for a block
generate_pnr_script() {
    local BLOCK=$1
    local OUTPUT_DIR="$PROJECT_DIR/blocks/$BLOCK/results"
    local SCRIPT_FILE="$OUTPUT_DIR/pnr_$BLOCK.tcl"

    mkdir -p "$OUTPUT_DIR"

    # Block-specific parameters
    # DIE_SIZE is calculated based on logic area + pins requirement
    # Many pins → need bigger die perimeter
    case $BLOCK in
        uart)
            TOP_MODULE="uart_wb"
            NETLIST="$OUTPUT_DIR/uart_wb_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/uart.sdc"
            # ~4200 µm² logic, ~140 pins → 150x150 µm die
            DIE_SIZE="150 150"
            ;;
        spi)
            TOP_MODULE="spi_wb"
            NETLIST="$OUTPUT_DIR/spi_wb_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/spi.sdc"
            # ~2400 µm² logic, ~140 pins → 140x140 µm
            DIE_SIZE="140 140"
            ;;
        timer)
            TOP_MODULE="timer_wb"
            NETLIST="$OUTPUT_DIR/timer_wb_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/timer.sdc"
            # ~5000 µm² logic, ~140 pins → 160x160 µm
            DIE_SIZE="160 160"
            ;;
        gpio)
            TOP_MODULE="gpio_wb"
            NETLIST="$OUTPUT_DIR/gpio_wb_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/gpio.sdc"
            # ~8000 µm² logic, ~240 pins → 200x200 µm
            DIE_SIZE="200 200"
            ;;
        bus)
            TOP_MODULE="wb_interconnect"
            NETLIST="$OUTPUT_DIR/wb_interconnect_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/bus.sdc"
            # ~1300 µm² logic but 626 pins! → 450x450 µm (pin-dominated)
            DIE_SIZE="450 450"
            ;;
        cpu)
            TOP_MODULE="cpu_wb_wrapper"
            NETLIST="$OUTPUT_DIR/cpu_wb_wrapper_synth.v"
            SDC="$PROJECT_DIR/constraints/blocks/cpu.sdc"
            # ~81000 µm² logic, ~200 pins → 450x450 µm
            DIE_SIZE="450 450"
            ;;
        *)
            echo "ERROR: Unknown block '$BLOCK'"
            echo "Available: uart, spi, timer, gpio, bus, cpu"
            exit 1
            ;;
    esac

    # Verify netlist exists
    if [ ! -f "$NETLIST" ]; then
        echo "ERROR: Netlist not found: $NETLIST"
        echo "Run synthesis first: ./run_synth.sh $BLOCK"
        exit 1
    fi

    # Generate the OpenROAD TCL script
    cat > "$SCRIPT_FILE" <<'OPENROAD_SCRIPT'
# ============================================================================
# Block P&R Script: __BLOCK__ (__TOP_MODULE__)
# Generated by run_pnr.sh
# ============================================================================

puts "=========================================="
puts "   Block P&R: __BLOCK__"
puts "=========================================="

# Paths
set platform_dir "__PLATFORM_DIR__"
set output_dir "__OUTPUT_DIR__"

#-------------------------------------------------------------------------------
# Load technology files
#-------------------------------------------------------------------------------
puts "\n>>> Loading LEF files..."
read_lef $platform_dir/lef/sky130_fd_sc_hd.tlef
read_lef $platform_dir/lef/sky130_fd_sc_hd_merged.lef

puts ">>> Loading Liberty files..."
read_liberty $platform_dir/lib/sky130_fd_sc_hd__tt_025C_1v80.lib

#-------------------------------------------------------------------------------
# Load design
#-------------------------------------------------------------------------------
puts "\n>>> Loading netlist..."
read_verilog __NETLIST__
link_design __TOP_MODULE__

puts ">>> Loading SDC constraints..."
read_sdc __SDC__

#-------------------------------------------------------------------------------
# FLOORPLAN
#-------------------------------------------------------------------------------
puts "\n>>> Initializing floorplan..."
# Use fixed die size (calculated based on logic area + pin count)
initialize_floorplan \
    -die_area "0 0 __DIE_W__ __DIE_H__" \
    -core_area "5 5 [expr {__DIE_W__ - 5}] [expr {__DIE_H__ - 5}]" \
    -site unithd

source $platform_dir/make_tracks.tcl

puts ">>> Placing I/O pins..."
place_pins -hor_layers met3 -ver_layers met2

puts ">>> Floorplan complete."
report_design_area

# Save floorplan checkpoint
write_def $output_dir/__TOP_MODULE___floorplan.def

#-------------------------------------------------------------------------------
# PLACEMENT
#-------------------------------------------------------------------------------
puts "\n>>> Running global placement..."
global_placement -density 0.7

puts ">>> Running detailed placement..."
detailed_placement

# Wire RC estimation
set_wire_rc -signal -layer met2
set_wire_rc -clock -layer met5

# Estimate parasitics and optimize
estimate_parasitics -placement
repair_design
repair_timing

# Re-legalize
detailed_placement
check_placement

puts ">>> Placement complete."
report_design_area

# Save placement checkpoint
write_def $output_dir/__TOP_MODULE___placed.def

#-------------------------------------------------------------------------------
# CLOCK TREE SYNTHESIS
#-------------------------------------------------------------------------------
puts "\n>>> Running CTS..."

set root_buffer "sky130_fd_sc_hd__clkbuf_16"
set buffer_list {
    sky130_fd_sc_hd__clkbuf_1
    sky130_fd_sc_hd__clkbuf_2
    sky130_fd_sc_hd__clkbuf_4
    sky130_fd_sc_hd__clkbuf_8
    sky130_fd_sc_hd__clkbuf_16
}

clock_tree_synthesis \
    -root_buf $root_buffer \
    -buf_list $buffer_list \
    -sink_clustering_enable \
    -sink_clustering_max_diameter 50 \
    -sink_clustering_size 20

repair_clock_nets
detailed_placement

# Post-CTS optimization
estimate_parasitics -placement
repair_timing
detailed_placement

puts ">>> CTS complete."
report_clock_skew

# Save CTS checkpoint
write_def $output_dir/__TOP_MODULE___cts.def

#-------------------------------------------------------------------------------
# ROUTING
#-------------------------------------------------------------------------------
puts "\n>>> Setting up routing..."

set_routing_layers -signal li1-met5 -clock met3-met5

# Power connections
add_global_connection -net VDD -pin_pattern "^VPWR$" -power
add_global_connection -net VDD -pin_pattern "^VPB$" -power
add_global_connection -net VSS -pin_pattern "^VGND$" -ground
add_global_connection -net VSS -pin_pattern "^VNB$" -ground
global_connect

# Fix tie-cell nets incorrectly marked as POWER/GROUND
# The 'one_' and 'zero_' nets are logic constants, not power rails
set block [ord::get_db_block]
foreach net [$block getNets] {
    set net_name [$net getName]
    set sig_type [$net getSigType]
    if {($sig_type == "POWER" || $sig_type == "GROUND") &&
        ([string match "*one_*" $net_name] || [string match "*zero_*" $net_name])} {
        puts "Reclassifying tie net: $net_name from $sig_type to SIGNAL"
        $net setSigType "SIGNAL"
    }
}

puts ">>> Running global routing..."
global_route

puts ">>> Running detailed routing..."
detailed_route

puts ">>> Routing complete."

# Save routed design
write_def $output_dir/__TOP_MODULE___routed.def

#-------------------------------------------------------------------------------
# REPORTS
#-------------------------------------------------------------------------------
puts "\n>>> Generating reports..."

report_design_area
report_worst_slack -max
report_worst_slack -min
report_tns
report_wns

# Save timing report
report_checks -path_delay max -fields {slew cap input_pins nets} \
    > $output_dir/__TOP_MODULE___timing.rpt

# Save area report
report_design_area > $output_dir/__TOP_MODULE___area.rpt

puts "\n=========================================="
puts "   P&R complete: __BLOCK__"
puts "=========================================="
puts "Results in: $output_dir"
OPENROAD_SCRIPT

    # Extract die width and height from DIE_SIZE
    DIE_W=$(echo $DIE_SIZE | awk '{print $1}')
    DIE_H=$(echo $DIE_SIZE | awk '{print $2}')

    # Substitute variables
    sed -i "s|__BLOCK__|$BLOCK|g" "$SCRIPT_FILE"
    sed -i "s|__TOP_MODULE__|$TOP_MODULE|g" "$SCRIPT_FILE"
    sed -i "s|__PLATFORM_DIR__|$PLATFORM_DIR|g" "$SCRIPT_FILE"
    sed -i "s|__OUTPUT_DIR__|$OUTPUT_DIR|g" "$SCRIPT_FILE"
    sed -i "s|__NETLIST__|$NETLIST|g" "$SCRIPT_FILE"
    sed -i "s|__SDC__|$SDC|g" "$SCRIPT_FILE"
    sed -i "s|__DIE_W__|$DIE_W|g" "$SCRIPT_FILE"
    sed -i "s|__DIE_H__|$DIE_H|g" "$SCRIPT_FILE"

    echo "$SCRIPT_FILE"
}

# Run P&R for a block
run_pnr() {
    local BLOCK=$1
    echo ""
    echo "=============================================="
    echo "  Place & Route: $BLOCK"
    echo "=============================================="

    SCRIPT_FILE=$(generate_pnr_script "$BLOCK")
    OUTPUT_DIR="$(dirname "$SCRIPT_FILE")"

    cd "$PROJECT_DIR"
    openroad "$SCRIPT_FILE" 2>&1 | tee "$OUTPUT_DIR/pnr_$BLOCK.log"

    echo ""
    echo "  Done: $BLOCK"
    echo "  DEF files in: $OUTPUT_DIR"
    echo "=============================================="
}

# Main
if [ $# -eq 0 ]; then
    echo "Usage: $0 <block_name|all>"
    echo "Blocks: uart, spi, timer, gpio, bus, cpu"
    exit 1
fi

if [ "$1" = "all" ]; then
    # Start with smallest blocks (faster, good for testing)
    for block in bus spi uart timer gpio cpu; do
        run_pnr "$block"
    done
    echo ""
    echo "All blocks completed!"
else
    run_pnr "$1"
fi
